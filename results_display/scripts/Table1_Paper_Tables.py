"""
Build the paper tables for Experiment 1 (Table1_Cindex_Main).

Organization (5 cohorts: BRCA/COAD/KIRC/KIRP/LIHC):
    Table1a_Cindex_Matrix.csv      c-index full matrix, mean±std per cohort,
                                   Mean C-index + Avg Rank
    Table1b_MultiMetric_Summary.csv  Mean C-index / Mean IBS / 2y AUC / 5y AUC
                                   / Avg Rank / p vs Ours (paired Wilcoxon +
                                   Holm, on per-(cohort,fold) c-index pairs)
    AppendixS1_IBS_Matrix.csv      IBS full matrix (mean±std)
    AppendixS2_AUC2y_Matrix.csv    2y td-AUC full matrix (mean±std)
    AppendixS3_AUC5y_Matrix.csv    5y td-AUC full matrix (mean±std); a cohort
                                   with too few 5y events falls back to 3y AUC
                                   (column annotated "(3y)")

Data sources (nothing intermediate is written into the display folders):
  - baselines: results/Table1_Cindex_Main/<test-dir>/ (c-index from
    test_result.csv; IBS/AUC recomputed in memory from the saved pkl logits)
  - Ours (main model C_film, final config t028_orig):
    results/Cfilm_Hparam_Eval/Table1_Cindex/ (only for --with-ours dirs)
  - cox rows (clinic_cox, C_film): IBS/AUC from the forward-only Breslow
    cache at results_display/.cache_table1/cox_ibs_auc_folds.csv when present
    (generated by Table1_CoxBreslow_Forward.py); otherwise "-".

Requires the SurvPGC conda env. Run from the project root:
    python results_display/scripts/Table1_Paper_Tables.py [--test-dir DIR]
"""

