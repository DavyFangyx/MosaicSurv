# 5-cohort scope per the current organization
COHORT_DISPLAY = [
    ("BRCA", "tcga_brca"),
    ("COAD", "tcga_coad"),
    ("KIRC", "tcga_kirc"),
    ("KIRP", "tcga_kirp"),
    ("LIHC", "tcga_lihc"),
]

OURS_RUN_FILTER = "t028_orig"  # final C_film config for Table 1
REF_MODEL = "C_film"  # main model; reference for "p vs Ours"
OURS_MODEL_DIR_TOKEN = "survtri_poe_vae_c_film"

FALLBACK_AUC_LANDMARK = 36.0  # Appendix S3 fallback for 5y-deficient cohorts
FALLBACK_MIN_EVENTS = 5

COX_CACHE_CSV = ".cache_table1/cox_ibs_auc_folds.csv"


def collect_cindex_folds(
    results_root: Path,
    group_dir: str,
    layer_dir: str,
    test_dir: str | None,
    *,
    ours_results_root: Path | None = None,
    ours_group_dir: str = "Table1_Cindex",
) -> dict[tuple[str, str], dict[int, float]]:
    """(study, model) -> {fold: test_cindex} for baselines + C_film (t028_orig)."""
    study_model_folds: dict[tuple[str, str], dict[int, float]] = {}

    for study_token, study in STUDY_SPECS:
        study_dir = resolve_group_study_dir(
            results_root,
            group_dir,
            layer_dir,
            test_dir,
            study_token,
            GROUP_CONFIG["baselines"]["results_suffix"],
        )
        if study_dir is None:
            continue
        for csv_path in sorted(study_dir.rglob("test_result.csv")):
            model = extract_model_name("baselines", csv_path)
            folds = load_csv_cindex_by_fold(csv_path)
            if folds:
                study_model_folds[(study, model)] = folds

    if ours_results_root is not None:
        for study_token, study in STUDY_SPECS:
            study_dir = resolve_group_study_dir(
                ours_results_root,
                ours_group_dir,
                layer_dir,
                None,
                study_token,
                GROUP_CONFIG["ours"]["results_suffix"],
            )
            if study_dir is None:
                continue
            for csv_path in sorted(study_dir.rglob("test_result.csv")):
                if f"__{OURS_RUN_FILTER}" not in csv_path.parents[1].name:
                    continue
                folds = load_csv_cindex_by_fold(csv_path)
                if folds:
                    study_model_folds[(study, REF_MODEL)] = folds
    return study_model_folds


def load_cox_fold_metrics(
    project_root: Path,
) -> dict[tuple[str, str], dict[int, dict[str, float]]]:
    """(study, model) -> {fold: metric dict} from the forward Breslow cache."""
    path = project_root / "results_display" / COX_CACHE_CSV
    if not path.is_file():
        return {}
    df = pd.read_csv(path)
    study_model_folds: dict[tuple[str, str], dict[int, dict[str, float]]] = {}
    for _, row in df.iterrows():
        model = str(row["model"])
        if model == OURS_MODEL_DIR_TOKEN:
            model = REF_MODEL
        key = (str(row["study"]), model)
        folds = study_model_folds.setdefault(key, {})
        folds[int(row["fold"])] = {
            "ibs": row["ibs"],
            "auc24": row["auc24"],
            "auc60": row["auc60"],
            "n_events_24": row["n_events_24"],
            "n_events_60": row["n_events_60"],
        }
    return study_model_folds


def recompute_cohort_landmark_folds(
    results_root: Path,
    group_dir: str,
    layer_dir: str,
    test_dir: str | None,
    study: str,
    landmark: float,
    min_events: int,
    bin_provider: BinProvider,
) -> dict[str, dict[int, float]]:
    """Offline AUC at an arbitrary landmark for every nll model of one cohort.

    Used by Appendix S3's 3y fallback for cohorts whose 5y AUC is unavailable.
    """
    model_folds: dict[str, dict[int, float]] = {}
    study_token = {study: token for token, study in STUDY_SPECS}.get(study, study)
    study_dir = resolve_group_study_dir(
        results_root,
        group_dir,
        layer_dir,
        test_dir,
        study_token,
        GROUP_CONFIG["baselines"]["results_suffix"],
    )
    if study_dir is None:
        return model_folds

    for csv_path in sorted(study_dir.rglob("test_result.csv")):
        model = extract_model_name("baselines", csv_path)
        if model in COX_BASELINE_MODELS:
            continue  # scalar Cox risk, no survival curve offline
        model_dir = csv_path.parent
        edges, cohort_surv = bin_provider.get_for_model_dir(study, model_dir)
        if edges is None or cohort_surv is None:
            continue
        for test_pkl in sorted(model_dir.glob("split_*_results.pkl")):
            fold = int(test_pkl.stem.split("_")[1])
            try:
                times, cens, _, logits = load_fold_pkl(test_pkl)
            except Exception:
                continue
            valid = times >= 0.0
            test_min, test_max = float(times[valid].min()), float(times[valid].max())
            n_events = int(
                ((cens[valid] < 1.0) & (times[valid] <= landmark)).sum()
            )
            if not (test_min <= landmark <= test_max and n_events >= min_events):
                model_folds.setdefault(model, {})[fold] = math.nan
                continue
            survival_columns = survival_columns_from_logits(logits[valid])
            estimate = 1.0 - interpolate_survival(
                survival_columns, edges[1:], np.array([landmark])
            )
            try:
                aucs = compute_landmark_aucs(
                    cohort_surv,
                    build_surv_object(times[valid], cens[valid]),
                    estimate,
                    [landmark],
                )
                # exact 0.0 = degenerate IPCW artifact on tiny event folds
                value = (
                    aucs[0] if math.isfinite(aucs[0]) and aucs[0] != 0.0 else math.nan
                )
            except Exception:
                value = math.nan
            model_folds.setdefault(model, {})[fold] = value
    return model_folds


def holm_correct(p_values: dict[str, float | None]) -> dict[str, float | None]:
    """Holm step-down across the valid p-values (smallest first)."""
    valid = [
        (model, p)
        for model, p in p_values.items()
        if p is not None and math.isfinite(p)
    ]
    valid.sort(key=lambda item: item[1])
    adjusted: dict[str, float | None] = {model: None for model in p_values}
    previous = 0.0
    n = len(valid)
    for rank, (model, p) in enumerate(valid, start=1):
        candidate = min(1.0, p * (n - rank + 1))
        previous = max(previous, candidate)
        adjusted[model] = previous
    return adjusted


def format_p(p: float | None) -> str:
    if p is None:
        return "-"
    if p < 0.001:
        return "<0.001"
    return f"{p:.3f}"


def compute_p_vs_ours(
    cindex_folds: dict[tuple[str, str], dict[int, float]],
    models: list[str],
) -> dict[str, float | None]:
    from scipy.stats import wilcoxon

    ref_folds = {
        (study, fold): value
        for (study, model), folds in cindex_folds.items()
        if model == REF_MODEL
        for fold, value in folds.items()
    }
    raw: dict[str, float | None] = {}
    for model in models:
        if model == REF_MODEL or not ref_folds:
            raw[model] = None
            continue
        diffs: list[float] = []
        for (study, fold), ref_value in ref_folds.items():
            value = cindex_folds.get((study, model), {}).get(fold)
            if value is None:
                continue
            if abs(value - ref_value) > 1e-12:
                diffs.append(value - ref_value)
        if len(diffs) < 2:
            raw[model] = None
            continue
        try:
            _, p = wilcoxon(diffs)
            raw[model] = float(p)
        except Exception:
            raw[model] = None
    return holm_correct(raw)


def build_tables(
    results_root: Path,
    output_root: Path,
    project_root: Path,
    *,
    group_dir: str,
    test_dir: str,
    layer_dir: str | None = None,
    output_name: str | None = None,
    ours_results_root: Path | None = None,
    ours_group_dir: str = "Table1_Cindex",
    with_cox_cache: bool = True,
) -> None:
    experiment_dir = results_root / group_dir / test_dir
    if layer_dir is None:
        layer_dir = infer_layer_dir(test_dir, experiment_dir)
    if not layer_dir:
        print(f"[WARN] Skip {test_dir}: cannot infer layer prefix")
        return
    output_name = output_name or test_dir
    print(f"[EXP] {test_dir} -> {output_name} (layer={layer_dir})")

    cindex_folds = collect_cindex_folds(
        results_root,
        group_dir,
        layer_dir,
        test_dir,
        ours_results_root=ours_results_root,
        ours_group_dir=ours_group_dir,
    )
    ours_present = any(model == REF_MODEL for _, model in cindex_folds)
    ours_specs = [("Ours", REF_MODEL)] if ours_present else []
    specs = BASELINE_MODEL_SPECS + ours_specs
    models = [model for _, model in specs]

    studies = [study for _, study in COHORT_DISPLAY]

    # ---- fold-level IBS/AUC: nll baselines recomputed in memory, cox from cache
    bin_provider = BinProvider()
    fold_metrics: dict[tuple[str, str], dict[int, dict[str, float]]] = {}
    for study_token, study in [s for s in STUDY_SPECS if s[1] in studies]:
        model_folds = collect_study_model_metrics(
            results_root,
            group_dir,
            layer_dir,
            test_dir,
            study_token,
            study,
            GROUP_CONFIG["baselines"]["results_suffix"],
            bin_provider,
        )
        for model, folds in model_folds.items():
            fold_metrics[(study, model)] = folds
    cox_folds = load_cox_fold_metrics(project_root) if with_cox_cache else {}
    for key, folds in cox_folds.items():
        fold_metrics[key] = folds

    # ---- per-cohort per-model aggregates
    cindex_text: dict[tuple[str, str], str] = {}
    cindex_mean: dict[tuple[str, str], float | None] = {}
    metric_mean: dict[str, dict[tuple[str, str], float | None]] = {
        metric: {} for metric in ("ibs", "auc24", "auc60")
    }

    for study in studies:
        for model in models:
            mean, std = mean_std(list(cindex_folds.get((study, model), {}).values()))
            cindex_mean[(study, model)] = mean
            cindex_text[(study, model)] = format_mean_std(mean, std)
        for model in models:
            folds = fold_metrics.get((study, model), {})
            for metric in ("ibs", "auc24", "auc60"):
                values = [f.get(metric, math.nan) for f in folds.values()]
                mean, _ = mean_std(values)
                metric_mean[metric][(study, model)] = mean

    # ---- Appendix S3: 5y AUC with 3y fallback for deficient cohorts
    fallback_columns: dict[str, float | None] = {}
    for study in studies:
        cohort_auc60 = [
            metric_mean["auc60"].get((study, model))
            for model in models
            if metric_mean["auc60"].get((study, model)) is not None
        ]
        if cohort_auc60:
            continue
        print(f"[FALLBACK] {study}: no 5y AUC available -> recomputing 3y AUC")
        fallback_folds = recompute_cohort_landmark_folds(
            results_root,
            group_dir,
            layer_dir,
            test_dir,
            study,
            FALLBACK_AUC_LANDMARK,
            FALLBACK_MIN_EVENTS,
            bin_provider,
        )
        for model in models:
            mean, _ = mean_std(list(fallback_folds.get(model, {}).values()))
            metric_mean["auc60"][(study, model)] = mean
            fallback_columns[study] = FALLBACK_AUC_LANDMARK

    # ---- Avg Rank (per cohort, average ranks on mean c-index, tie-averaged)
    from scipy.stats import rankdata

    model_ranks: dict[str, list[float]] = {model: [] for model in models}
    for study in studies:
        present = {
            m: v
            for m, v in ((m, cindex_mean.get((study, m))) for m in models)
            if v is not None
        }
        if not present:
            continue
        names = list(present)
        ranks = rankdata([-present[m] for m in names], method="average")
        for name, rank in zip(names, ranks):
            model_ranks[name].append(rank)
    avg_rank = {
        model: sum(ranks) / len(ranks) if ranks else None
        for model, ranks in model_ranks.items()
    }

    # ---- p vs Ours
    p_vs_ours = compute_p_vs_ours(cindex_folds, models)

    def mean_of_metric(metric: str, model: str) -> float | None:
        values = [
            metric_mean[metric].get((study, model))
            for study in studies
            if metric_mean[metric].get((study, model)) is not None
        ]
        return sum(values) / len(values) if values else None

    def mean_of_cindex(model: str) -> float | None:
        values = [
            cindex_mean.get((study, model)) for study in studies
        ]
        values = [v for v in values if v is not None]
        return sum(values) / len(values) if values else None

    # ---- Table1a
    rows1a: list[dict[str, object]] = []
    for model_type, model in specs:
        row: dict[str, object] = {"Model Type": model_type, "Model": model}
        for display, study in COHORT_DISPLAY:
            row[display] = cindex_text.get((study, model), "-")
        mean = mean_of_cindex(model)
        row["Mean C-index↑"] = f"{mean:.4f}" if mean is not None else "-"
        row["Avg Rank↓"] = (
            f"{avg_rank[model]:.2f}" if avg_rank[model] is not None else "-"
        )
        rows1a.append(row)
    table1a = pd.DataFrame(rows1a)

    # ---- Table1b
    rows1b: list[dict[str, object]] = []
    for model_type, model in specs:
        mean = mean_of_cindex(model)
        rows1b.append(
            {
                "Model Type": model_type,
                "Model": model,
                "Mean C-index↑": f"{mean:.4f}" if mean is not None else "-",
                "Mean IBS↓": f"{mean_of_metric('ibs', model):.4f}"
                if mean_of_metric("ibs", model) is not None
                else "-",
                "2y AUC↑": f"{mean_of_metric('auc24', model):.4f}"
                if mean_of_metric("auc24", model) is not None
                else "-",
                "5y AUC↑": f"{mean_of_metric('auc60', model):.4f}"
                if mean_of_metric("auc60", model) is not None
                else "-",
                "Avg Rank": f"{avg_rank[model]:.2f}"
                if avg_rank[model] is not None
                else "-",
                "p vs Ours": format_p(p_vs_ours.get(model))
                if model != REF_MODEL
                else "-",
            }
        )
    table1b = pd.DataFrame(rows1b)

    # ---- Appendices S1/S2/S3
    def appendix_matrix(metric: str, mean_col: str) -> pd.DataFrame:
        rows: list[dict[str, object]] = []
        for model_type, model in specs:
            row: dict[str, object] = {"Model Type": model_type, "Model": model}
            for display, study in COHORT_DISPLAY:
                mean = metric_mean[metric].get((study, model))
                if mean is None:
                    row[display] = "-"
                    continue
                folds = fold_metrics.get((study, model), {})
                values = [f.get(metric, math.nan) for f in folds.values()]
                _, std = mean_std(values)
                row[display] = format_mean_std(mean, std)
            row[mean_col] = (
                f"{mean_of_metric(metric, model):.4f}"
                if mean_of_metric(metric, model) is not None
                else "-"
            )
            rows.append(row)
        return pd.DataFrame(rows)

    s1 = appendix_matrix("ibs", "Mean IBS")
    s2 = appendix_matrix("auc24", "Mean 2y AUC")
    s3 = appendix_matrix("auc60", "Mean 5y AUC")

    # annotate fallback columns on S3
    if fallback_columns:
        rename = {
            display: f"{display} (3y)"
            for display, study in COHORT_DISPLAY
            if study in fallback_columns
        }
        s3 = s3.rename(columns=rename)

    out_dir = output_root / group_dir / output_name
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, df in [
        ("Table1a_Cindex_Matrix.csv", table1a),
        ("Table1b_MultiMetric_Summary.csv", table1b),
        ("AppendixS1_IBS_Matrix.csv", s1),
        ("AppendixS2_AUC2y_Matrix.csv", s2),
        ("AppendixS3_AUC5y_Matrix.csv", s3),
    ]:
        df.to_csv(out_dir / name, index=False)
        print(f"[WRITE] {output_name}/{name}")


def main() -> None:
    project_root = project_root_from_script()
    parser = argparse.ArgumentParser(
        description="Build Table1a/1b/S1-S3 paper tables"
    )
    parser.add_argument(
        "--results_root",
        type=Path,
        default=project_root / "results",
        help="Root results directory (baselines)",
    )
    parser.add_argument(
        "--output_root",
        type=Path,
        default=project_root / "results_display",
        help="Root output directory",
    )
    parser.add_argument("--group-dir", default="Table1_Cindex_Main")
    parser.add_argument("--layer-dir", default=None)
    parser.add_argument("--test-dir", default=None)
    parser.add_argument(
        "--ours-results-root",
        type=Path,
        default=project_root / "results" / "Cfilm_Hparam_Eval",
        help="Results root for the C_film main model",
    )
    parser.add_argument(
        "--with-ours-test-dirs",
        default="L0Test After fixed modal missing",
        help="Comma-separated experiment dirs that get the Ours (C_film) row",
    )
    parser.add_argument(
        "--cox-cache-dirs",
        default="L0Test_BeforeTune,L0Test After Fix some err,L0Test After fixed modal missing",
        help="Comma-separated dirs whose clinic_cox runs match the Breslow cache",
    )
    args = parser.parse_args()

    ours_for_dirs = {
        part.strip() for part in args.with_ours_test_dirs.split(",") if part.strip()
    }
    cox_cache_dirs = {
        part.strip() for part in args.cox_cache_dirs.split(",") if part.strip()
    }

    def run_one(test_dir: str) -> None:
        build_tables(
            args.results_root,
            args.output_root,
            project_root,
            group_dir=args.group_dir,
            test_dir=test_dir,
            layer_dir=args.layer_dir,
            ours_results_root=args.ours_results_root if test_dir in ours_for_dirs else None,
            with_cox_cache=test_dir in cox_cache_dirs,
        )

    if args.test_dir is not None:
        run_one(args.test_dir)
        print("Done.")
        return

    for experiment_dir in list_experiment_dirs(args.results_root, args.group_dir):
        run_one(experiment_dir.name)
    print("Done.")


if __name__ == "__main__":
    main()
